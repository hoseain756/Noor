"""Generate synchronous Flutter localization catalogs from canonical ARB files."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
out = ['// Generated by tool/generate_nova_l10n.py. Edit the ARB sources.\n']
for locale, name in [('en', 'novaEnglish'), ('ar', 'novaArabic')]:
    data = json.loads((root / f'lib/l10n/app_{locale}.arb').read_text(encoding='utf-8'))
    values = {k: v for k, v in data.items() if not k.startswith('@')}
    out.append(f'const Map<String, String> {name} = {{\n')
    for k, v in values.items():
        # JSON escaping is valid in Dart strings except interpolation dollars.
        out.append(f'  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False).replace(chr(36), chr(92)+chr(36))},\n')
    out.append('};\n')
(root/'lib/l10n/nova_messages.g.dart').write_text(''.join(out), encoding='utf-8')
print(f'Generated {len(values)} localized messages for each language')
